#!/usr/bin/env python3
"""Generate the identical bit layout for the UART bridge and its host driver."""
import json
import hashlib
import re
import os
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


def write_generated(path, text):
    if path.exists() and path.read_text()==text:
        return
    with tempfile.NamedTemporaryFile(mode="w",dir=path.parent,prefix=path.name+".",delete=False) as output:
        output.write(text)
        temporary=output.name
    os.chmod(temporary,0o644)
    os.replace(temporary,path)


def main():
    layout = json.loads((ROOT / "fpga/ports.json").read_text())
    defaults = {name:int(value) for name,value in re.findall(r"parameter integer (\w+)\s*=\s*(\d+)", (ROOT/"rtl/wasmetal_core.sv").read_text())}
    expected={"VALUE_DEPTH","CONTROL_DEPTH","CALL_DEPTH","MEMORY_COUNT","HEAP_SLOTS"}
    if set(defaults)!=expected:
        raise ValueError("core parameter declarations changed; update the configuration generator")
    schema_id=int(hashlib.sha256(json.dumps(layout,sort_keys=True).encode()).hexdigest()[:8],16)
    sizes = {d: sum(p["width"] for p in ports) for d, ports in layout.items()}
    sv = ["// Generated by tools/generate_fpga_ports.py; edit fpga/ports.json."]
    sv.append(f"localparam [31:0] SCHEMA_ID=32'h{schema_id:08x};")
    sv.append(f"localparam integer HEAP_CAPACITY={defaults['HEAP_SLOTS']};")
    header = ["// Generated by tools/generate_fpga_ports.py; edit fpga/ports.json.",
              "#pragma once", "#include <array>", "#include <cstdint>", "#include <vector>",
              "struct FpgaPorts {", "    using Bits = std::array<uint32_t,4>;", "    uint8_t clk=0;"]
    header.append(f"    static constexpr uint32_t SCHEMA_ID=0x{schema_id:08x};")
    for direction in ("input", "output"):
        count = (sizes[direction]+7)//8
        sv.append(f"localparam integer {direction.upper()}_BYTES={count};")
        header.append(f"    static constexpr unsigned {direction.upper()}_BYTES={count};")
        offset = 0
        for port in layout[direction]:
            name, width = port["name"], port["width"]
            sv.append(f"wire [{width-1}:0] core_{name};")
            if direction == "input":
                sv.append(f"assign core_{name}=active_inputs[{offset}+:{width}];")
            else:
                sv.append(f"assign outgoing_outputs[{offset}+:{width}]=core_{name};")
            ty = "Bits" if width > 64 else "uint64_t" if width > 32 else "uint32_t" if width > 8 else "uint8_t"
            header.append(f"    {ty} {name}{{}};")
            offset += width
        if direction == "output" and offset < count*8:
            sv.append(f"assign outgoing_outputs[{count*8-1}:{offset}]=0;")
    sv.extend(["`ifdef WASMETAL_MAPPED_CORE", "wasmetal_core core(", "`else",
               "wasmetal_core #(.VALUE_DEPTH(VALUE_DEPTH),.CONTROL_DEPTH(128),.CALL_DEPTH(64),.MEMORY_COUNT(16),.HEAP_SLOTS(HEAP_CAPACITY)) core(", "`endif"])
    connections = [".clk(core_clock)"]+[f".{p['name']}(core_{p['name']})" for d in ("input", "output") for p in layout[d]]
    sv.append("    "+",\n    ".join(connections)+");")
    header.extend([
        "    static void write_bits(std::vector<uint8_t>& bytes,unsigned offset,unsigned width,const Bits& value) {",
        "        for(unsigned bit=0;bit<width;bit++) bytes[(offset+bit)/8]|=uint8_t(((value[bit/32]>>(bit%32))&1U)<<((offset+bit)%8));",
        "    }",
        "    static Bits read_bits(const std::vector<uint8_t>& bytes,unsigned offset,unsigned width) {",
        "        Bits value{}; for(unsigned bit=0;bit<width;bit++) value[bit/32]|=uint32_t((bytes[(offset+bit)/8]>>((offset+bit)%8))&1U)<<(bit%32); return value;",
        "    }",
        "    std::vector<uint8_t> pack_inputs() const { std::vector<uint8_t> bytes(INPUT_BYTES,0);",
    ])
    offset=0
    for p in layout["input"]:
        n,w=p["name"],p["width"]
        value=n if w>64 else "Bits{uint32_t("+n+"),uint32_t(uint64_t("+n+")>>32),0,0}"
        header.append(f"        write_bits(bytes,{offset},{w},{value});")
        offset+=w
    header.extend(["        return bytes; }", "    void unpack_outputs(const std::vector<uint8_t>& bytes) {"])
    offset=0
    for p in layout["output"]:
        n,w=p["name"],p["width"]
        header.append(f"        {{ auto v=read_bits(bytes,{offset},{w}); "+(f"{n}=v;" if w>64 else f"{n}=decltype({n})(uint64_t(v[0])|(uint64_t(v[1])<<32));")+" }")
        offset+=w
    header.extend(["    }", "};"])
    write_generated(ROOT / "fpga/core_ports.svh","\n".join(sv)+"\n")
    write_generated(ROOT / "sim/fpga_ports.hpp","\n".join(header)+"\n")
    write_generated(ROOT / "sim/core_config.hpp","// Generated by tools/generate_fpga_ports.py.\n#pragma once\nnamespace core_config {\n"+
        "".join(f"inline constexpr unsigned {name}={value};\n" for name,value in sorted(defaults.items()))+"}\n")
    print(f"Generated {sizes['input']} input bits and {sizes['output']} output bits")


if __name__ == "__main__":
    main()
